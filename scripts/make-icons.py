"""Writes shared/icons.ts from the Claude desktop app's own icon font.

    python scripts/make-icons.py <anthropicons.woff2> <names.txt> shared/icons.ts

<anthropicons.woff2> is the font the app ships (its ion-dist.asar holds it);
<names.txt> lists `Name:codepoint` lines, as the app's bundle maps them.
Needs fontTools and brotli.
"""
import re, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

font_path, names_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
wanted = ['Atom', 'CaretDown', 'CaretRight', 'Check', 'Checklist', 'CommandLine', 'Copy', 'File',
          'Folder', 'FolderOpen', 'GitBranch', 'Github', 'Info', 'MapPin', 'Plugin', 'Search', 'X']
codes = {}
for line in open(names_path, encoding='utf-8'):
    name, code = line.strip().split(':')
    codes[name] = int(code)
font = TTFont(font_path)
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
rows = []
for name in wanted:
    glyph = glyphs[cmap[codes[name]]]
    pen = SVGPathPen(glyphs)
    glyph.draw(pen)
    d = pen.getCommands()
    assert re.fullmatch(r'[MLHVQCZ0-9 .\-]+', d), name
    key = name[0].lower() + name[1:]
    rows.append(f"  {key}: '{d}',")
body = '\n'.join(rows)
source = f"""// Generated by scripts/make-icons.py from the desktop app's icon font. Don't edit by hand.

import type {{ RenderElement, SvgProps }} from 'claude-code'

/** Each icon's outline: font units, y up, on a 1000-unit em. */
export const ICONS = {{
{body}
}} as const

export type IconName = keyof typeof ICONS

export function iconSource(name: IconName, ink = 'currentColor'): string {{
  return (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000">' +
    `<path fill="${{ink}}" transform="matrix(1 0 0 -1 0 1000)" d="${{ICONS[name]}}"/></svg>`
  )
}}

// A Client region's Svg can't follow the theme, so it is a grey with 3:1
// contrast on light and dark. The region's element table has no Svg, but the
// desktop draws one, so the element is written out by hand.
export function regionIcon(name: IconName, size: number, alt: string = name): RenderElement {{
  const props: SvgProps = {{ source: iconSource(name, '#8a8a8a'), alt, width: size, height: size }}
  return {{ type: 'Svg', props }} as RenderElement
}}
"""
open(out_path, 'w', encoding='utf-8', newline='\n').write(source)
print('wrote', len(wanted), 'icons,', len(source), 'chars')
